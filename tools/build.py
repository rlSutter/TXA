#!/usr/bin/env python3
"""build.py - build TXA's M0 probe.

  python3 tools/build.py            -> build/

Steps: generate the font and pictures; assemble src/txaprobe.a99 into E/A
option 5 files (xas99 -i); pack those into a disk image (xdm99) and into a
FinalGROM cartridge whose loader copies the same image into RAM; check the
memory map (the kernel must stay below >2FFE, the resident program
below >E000).

Outputs: build/TXAP1, TXAP2 (E/A 5 files), build/txaprobe.dsk (SSSD disk
image with both), build/txaprobe8.bin (cartridge), build/probe.lst.
XAS99 / XDM99 default to ../xdt99 next to the repository."""
import glob, os, subprocess, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
XDT = os.environ.get('XDT99', os.path.join(os.path.dirname(ROOT), 'xdt99'))
XAS = os.environ.get('XAS99', os.path.join(XDT, 'xas99.py'))
XDM = os.environ.get('XDM99', os.path.join(XDT, 'xdm99.py'))
B = os.path.join(ROOT, 'build')

def run(cmd, cwd=None):
    r = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    out = (r.stdout + r.stderr)
    errs = [l for l in out.splitlines() if 'Error' in l or 'error' in l]
    if r.returncode or errs:
        print(out); sys.exit('build failed: ' + ' '.join(cmd[:2]))
    return out

def ea5_segments(prefix):
    """Read the E/A 5 chain: [(address, bytes)] in file order."""
    segs, name = [], prefix
    while True:
        d = open(os.path.join(B, name), 'rb').read()
        flag, length, addr = (int.from_bytes(d[i:i + 2], 'big') for i in (0, 2, 4))
        segs.append((addr, d[6:length]))
        if not flag:
            return segs
        name = name[:-1] + chr(ord(name[-1]) + 1)

def cart_from_segments(segs, name, extra=b'', out=None):
    """A FinalGROM cartridge: the loader in bank 0, the E/A 5 image in
    banks 1.., then `extra` (the story) from the next bank boundary.
    Returns (cartridge bytes, first bank of extra)."""
    image, pieces = bytearray(), []
    for addr, data in segs:
        off = 0
        while off < len(data):
            pos = len(image)
            bank, boff = 1 + pos // 0x2000, pos % 0x2000
            n = min(len(data) - off, 0x2000 - boff)
            pieces.append((bank, 0x6000 + boff, addr + off, n))
            image += data[off:off + n]; off += n
    with open(os.path.join(ROOT, 'src/gen/cartsegs.a99'), 'w') as f:
        f.write('* cartsegs.a99 - GENERATED by tools/build.py: bank, window address, RAM address, bytes\nSEGTAB\n')
        for p in pieces:
            f.write('       DATA %d,>%04X,>%04X,%d\n' % p)
        f.write('       DATA >FFFF\n')
    with open(os.path.join(ROOT, 'src/gen/cartname.a99'), 'w') as f:
        f.write(f"* cartname.a99 - GENERATED by tools/build.py: the menu name\n       BYTE {len(name)}\n       TEXT '{name}'\n")
    run([sys.executable, XAS, '-R', '-b', '-o', '../build/cartldr.bin', 'cartldr.a99'], cwd=os.path.join(ROOT, 'src'))
    ldr = open(os.path.join(B, 'cartldr.bin'), 'rb').read()
    assert len(ldr) <= 0x2000
    body = bytearray(ldr.ljust(0x2000, b'\0')) + image
    body = body.ljust((len(body) + 0x1FFF) // 0x2000 * 0x2000, b'\0')
    first_extra = len(body) // 0x2000
    body += extra
    nb = (len(body) + 0x1FFF) // 0x2000
    banks = 1
    while banks < nb:
        banks *= 2                     # FinalGROM images: a power of two of 8K banks
    return bytes(body.ljust(banks * 0x2000, b'\0')), first_extra

def engine_cart(story_image, name='TXA STORY'):
    """Assemble the engine and build a cartridge carrying story_image.
    Two passes: the engine's size decides the story's first bank."""
    os.makedirs(os.path.join(ROOT, 'src/gen'), exist_ok=True)
    if not os.path.exists(os.path.join(ROOT, 'src/gen/font.a99')):
        subprocess.run([sys.executable, 'tools/mkfont.py'], cwd=ROOT, check=True)
    def storysrc(bank):
        with open(os.path.join(ROOT, 'src/gen/storysrc.a99'), 'w') as f:
            f.write('* storysrc.a99 - GENERATED by tools/build.py: where the story is in the cartridge\n'
                    f'STBNK1 DATA {bank}\nSTLENH DATA {len(story_image) >> 16}\nSTLENL DATA >{len(story_image) & 0xFFFF:04X}\n')
    first = None
    for _ in range(3):
        storysrc(first or 1)
        for f in glob.glob(os.path.join(B, 'TXAE*')):
            os.remove(f)
        run([sys.executable, XAS, '-R', '-i', '-L', '../build/engine.lst', '-E', '../build/engine.equ', '-o', '../build/TXAE1', 'txaeng.a99'],
            cwd=os.path.join(ROOT, 'src'))
        segs = ea5_segments('TXAE1')
        for addr, data in segs:
            if addr == 0x2000 and addr + len(data) > 0x2FFE:
                sys.exit('the kernel reaches >2FFE (AMSSIZ uses it)')
            if addr == 0xA000 and addr + len(data) > 0xD000:
                sys.exit(f'the resident engine ends at >{addr + len(data):04X}, past >D000 (window D)')
        cart, f2 = cart_from_segments(segs, name, story_image)
        if f2 == first:
            return cart, segs
        first = f2
    sys.exit('engine build did not settle')

def symbols(equ):
    """Label -> address from xas99's -E output ("label:" then "equ >XXXX")."""
    import re
    syms, last = {}, None
    for line in open(equ):
        m = re.match(r'^(\w+):\s*$', line)
        if m:
            last = m.group(1).upper(); continue
        m = re.match(r'^\s+equ\s+>([0-9A-Fa-f]{4})', line)
        if m and last:
            syms[last] = int(m.group(1), 16); last = None
    return syms

def main():
    os.makedirs(B, exist_ok=True)
    env = dict(os.environ, PYTHONPATH=os.path.join(ROOT, 'tools'))
    subprocess.run([sys.executable, 'tools/mkfont.py'], cwd=ROOT, check=True)
    subprocess.run([sys.executable, 'tools/mkpics.py'], cwd=ROOT, check=True, env=env, capture_output=True)
    for f in glob.glob(os.path.join(B, 'TXAP*')):
        os.remove(f)
    out = run([sys.executable, XAS, '-R', '-i', '-L', '../build/probe.lst', '-o', '../build/TXAP1', 'txaprobe.a99'],
              cwd=os.path.join(ROOT, 'src'))
    segs = ea5_segments('TXAP1')
    for addr, data in segs:
        end = addr + len(data)
        print(f'segment >{addr:04X}->{end - 1:04X}  {len(data)} bytes')
        if addr == 0x2000 and end > 0x2FFE:     # AMSSIZ overwrites >2FFE while it runs
            sys.exit('the kernel reaches >2FFE, which AMSSIZ uses while it counts SAMS pages')
        if addr >= 0xA000 and end > 0xE000:
            sys.exit('resident program runs into >E000 (the SAMS sizing window)')
    assert segs[0][0] == 0x2000, 'the first E/A 5 file must be the kernel at >2000 (KENTRY)'
    # the disk image
    dsk = os.path.join(B, 'txaprobe.dsk')
    if os.path.exists(dsk):
        os.remove(dsk)
    names = sorted(os.path.basename(f) for f in glob.glob(os.path.join(B, 'TXAP?')))
    run([sys.executable, XDM, dsk, '-X', 'sssd', '-n', 'TXAPROBE'])
    run([sys.executable, XDM, dsk, '-a'] + names + ['-f', 'PROGRAM'], cwd=B)
    # the cartridge: banks 1.. hold the image, split into per-bank pieces
    image, pieces = bytearray(), []
    for addr, data in segs:
        off = 0
        while off < len(data):
            pos = len(image)
            bank, boff = 1 + pos // 0x2000, pos % 0x2000
            n = min(len(data) - off, 0x2000 - boff)
            pieces.append((bank, 0x6000 + boff, addr + off, n))
            image += data[off:off + n]; off += n
    with open(os.path.join(ROOT, 'src/gen/cartsegs.a99'), 'w') as f:
        f.write('* cartsegs.a99 - GENERATED by tools/build.py: bank, window address, RAM address, bytes\nSEGTAB\n')
        for p in pieces:
            f.write('       DATA %d,>%04X,>%04X,%d\n' % p)
        f.write('       DATA >FFFF\n')
    with open(os.path.join(ROOT, 'src/gen/cartname.a99'), 'w') as f:
        f.write("* cartname.a99 - GENERATED by tools/build.py: the menu name\n       BYTE 9\n       TEXT 'TXA PROBE'\n")
    run([sys.executable, XAS, '-R', '-b', '-o', '../build/cartldr.bin', 'cartldr.a99'], cwd=os.path.join(ROOT, 'src'))
    ldr = open(os.path.join(B, 'cartldr.bin'), 'rb').read()
    assert len(ldr) <= 0x2000
    nb = 1 + (len(image) + 0x1FFF) // 0x2000
    banks = 1
    while banks < nb:
        banks *= 2                     # FinalGROM images: a power of two of 8K banks
    cart = bytearray(ldr.ljust(0x2000, b'\0')) + image.ljust((banks - 1) * 0x2000, b'\0')
    open(os.path.join(B, 'txaprobe8.bin'), 'wb').write(cart)
    print(f'build/TXAP1..  build/txaprobe.dsk  build/txaprobe8.bin ({len(cart) // 1024}K, {banks} banks)')

if __name__ == '__main__':
    main()
