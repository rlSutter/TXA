#!/usr/bin/env python3
"""build.py - build TXA's M0 probe.

  python3 tools/build.py            -> build/

Steps: generate the font and pictures; assemble src/txaprobe.a99 into E/A
option 5 files (xas99 -i); pack those into a disk image (xdm99) and into a
FinalGROM cartridge whose loader copies the same image into RAM; check the
memory map (the kernel must stay below >2FFE, the resident program
below >E000).

Outputs: build/TXAP1, TXAP2 (E/A 5 files), build/txaprobe.dsk (SSSD disk
image with both), build/txaprobe8.bin (cartridge), build/probe.lst.
XAS99 / XDM99 default to ../xdt99 next to the repository."""
import glob, os, subprocess, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
XDT = os.environ.get('XDT99', os.path.join(os.path.dirname(ROOT), 'xdt99'))
XAS = os.environ.get('XAS99', os.path.join(XDT, 'xas99.py'))
XDM = os.environ.get('XDM99', os.path.join(XDT, 'xdm99.py'))
B = os.path.join(ROOT, 'build')

def run(cmd, cwd=None):
    r = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    out = (r.stdout + r.stderr)
    errs = [l for l in out.splitlines() if 'Error' in l or 'error' in l]
    if r.returncode or errs:
        print(out); sys.exit('build failed: ' + ' '.join(cmd[:2]))
    return out

def check_ramvars():
    """No two variables in defs.a99's RAMVAR area may overlap.  A variable's
    size is the "N bytes" in its comment, or one word.  (A status-line
    buffer once overwrote the command history's counters.)"""
    import re
    vars_ = []
    for line in open(os.path.join(ROOT, 'src/defs.a99')):
        m = re.match(r'^(\w+)\s+EQU\s+RAMVAR\+>([0-9A-Fa-f]+)\s*(.*)$', line)
        if m:
            size = re.search(r'(\d+) bytes', m.group(3))
            n = int(size.group(1)) if size else 2
            words = re.search(r'(\d+) words', m.group(3))
            if words and not size:
                n = 2 * int(words.group(1))
            vars_.append((int(m.group(2), 16), n, m.group(1)))
    vars_.sort()
    for (a, n, name), (b, _, nxt) in zip(vars_, vars_[1:]):
        if a + n > b:
            sys.exit(f'defs.a99: {name} (>{a:03X}, {n} bytes) overlaps {nxt} (>{b:03X})')
    end = max(a + n for a, n, _ in vars_)
    if end > 0x700:
        sys.exit(f'defs.a99: the variables run to RAMVAR+>{end:03X}, past >700 (the return stack)')

def ea5_segments(prefix):
    """Read the E/A 5 chain: [(address, bytes)] in file order."""
    segs, name = [], prefix
    while True:
        d = open(os.path.join(B, name), 'rb').read()
        flag, length, addr = (int.from_bytes(d[i:i + 2], 'big') for i in (0, 2, 4))
        segs.append((addr, d[6:length]))
        if not flag:
            return segs
        name = name[:-1] + chr(ord(name[-1]) + 1)

def cart_from_segments(segs, name, extra=b'', out=None, pre=()):
    """A FinalGROM cartridge: the loader in bank 0, then the banks in `pre`
    (8K each, not loaded: the workbench's overlays, which it copies from
    the cartridge itself), then the E/A 5 image, then `extra` (the story)
    from the next bank boundary.
    A segment is (address, data) or (address, data, SAMS page): a paged
    one is copied into that page through its address's 4K window (it
    must not cross a window).  Returns (cartridge bytes, first bank of
    extra)."""
    image, pieces = bytearray(), []
    for b in pre:
        assert len(b) <= 0x2000, 'a pre bank is more than 8K'
        image += bytes(b) + bytes(0x2000 - len(b))
    for seg in segs:
        addr, data = seg[0], seg[1]
        page = seg[2] if len(seg) > 2 else 0
        if page:
            assert (addr & 0xF000) == ((addr + len(data) - 1) & 0xF000), 'a paged segment crosses a 4K window'
        off = 0
        while off < len(data):
            pos = len(image)
            bank, boff = 1 + pos // 0x2000, pos % 0x2000
            n = min(len(data) - off, 0x2000 - boff)
            pieces.append((bank, 0x6000 + boff, addr + off, n, page))
            image += data[off:off + n]; off += n
    with open(os.path.join(ROOT, 'src/gen/cartsegs.a99'), 'w') as f:
        f.write('* cartsegs.a99 - GENERATED by tools/build.py: bank, window address, RAM address, bytes, SAMS page\nSEGTAB\n')
        for p in pieces:
            f.write('       DATA %d,>%04X,>%04X,%d,%d\n' % p)
        f.write('       DATA >FFFF\n')
    with open(os.path.join(ROOT, 'src/gen/cartname.a99'), 'w') as f:
        f.write(f"* cartname.a99 - GENERATED by tools/build.py: the menu name\n       BYTE {len(name)}\n       TEXT '{name}'\n")
    run([sys.executable, XAS, '-R', '-b', '-o', '../build/cartldr.bin', 'cartldr.a99'], cwd=os.path.join(ROOT, 'src'))
    ldr = open(os.path.join(B, 'cartldr.bin'), 'rb').read()
    assert len(ldr) <= 0x2000
    body = bytearray(ldr.ljust(0x2000, b'\0')) + image
    body = body.ljust((len(body) + 0x1FFF) // 0x2000 * 0x2000, b'\0')
    first_extra = len(body) // 0x2000
    body += extra
    nb = (len(body) + 0x1FFF) // 0x2000
    banks = 1
    while banks < nb:
        banks *= 2                     # FinalGROM images: a power of two of 8K banks
    return bytes(body.ljust(banks * 0x2000, b'\0')), first_extra

def story_blob(story_image, pictures=b'', sounds=b''):
    """What the engine loads into SAMS: the story image, then the picture
    area and the sound area, each from a fresh 4K page when present.
    Returns (blob, the picture area's page, the sound area's page); a page
    of 0 means none."""
    blob, picpg, sndpg = story_image, 0, 0
    if pictures:
        blob += bytes((-len(blob)) % 4096); picpg = len(blob) // 4096; blob += pictures
    if sounds:
        blob += bytes((-len(blob)) % 4096); sndpg = len(blob) // 4096; blob += sounds
    return blob, picpg, sndpg

def write_storysrc(story_image, bank=1, disk_prefix=None, picpg=0, sndpg=0):
    """gen/storysrc.a99: where the engine finds the story.  From disk (M6:
    the generic engine, disk_prefix given): the story's length and its
    picture and sound pages are found at load time, and the name field is
    a placeholder that patch_engine_name fills in when the engine files are
    written.  From the cartridge (from bank on): the blob's length and
    pages, as built."""
    with open(os.path.join(ROOT, 'src/gen/storysrc.a99'), 'w') as f:
        f.write('* storysrc.a99 - GENERATED by tools/build.py: where the story is\n')
        if disk_prefix:
            f.write('STMODE DATA 1\nSTBNK1 DATA 0\nSTLENH DATA 0\nSTLENL DATA 0\n'
                    'PICPG  DATA 0\nSNDPG  DATA 0\n')
        else:
            f.write(f'STMODE DATA 0\nSTBNK1 DATA {bank}\nSTLENH DATA {len(story_image) >> 16}\n'
                    f'STLENL DATA >{len(story_image) & 0xFFFF:04X}\nPICPG  DATA {picpg}\nSNDPG  DATA {sndpg}\n')
        name = (disk_prefix or 'DSK1.STORY').ljust(NAMEFLD)[:NAMEFLD]
        f.write(f"       TEXT '{NAMEMARK}'\nSTNAME BYTE {len((disk_prefix or 'DSK1.STORY'))}\n       TEXT '{name}'\n       EVEN\n")

NAMEMARK = 'TXANAME:'                 # marks the engine's story-name field
NAMEFLD = 16                          # its room: device, '.', prefix (DSK1.ABCDEF is 11)

def patch_engine_name(data, device, prefix):
    """The engine's story-name field (after NAMEMARK) set to device.prefix:
    data is bytes of an E/A 5 file or an engine image; returns the patched
    bytes, or None when the field is not in it."""
    i = data.find(NAMEMARK.encode())
    if i < 0:
        return None
    name = f'{device}.{prefix}'.encode()
    assert len(name) <= NAMEFLD, name
    j = i + len(NAMEMARK)
    return data[:j] + bytes([len(name)]) + name.ljust(NAMEFLD, b' ') + data[j + 1 + NAMEFLD:]

def generic_engine_files(chunk=4096):
    """The generic disk engine (M6, D1): assembled once with a placeholder
    story name (gen/storysrc.a99 in disk mode); returns its E/A 5 program
    files' bytes in chain order.  The chain is cut into files of at most
    `chunk` bytes of code (M6 part 3: the workbench writes them through the
    disk buffer in VRAM, about 6K), never inside the story-name field;
    patch_engine_name gives a game its name."""
    write_storysrc(b'', disk_prefix='DSK1.STORY')
    assemble_engine('TXAG1')
    segs = ea5_segments('TXAG1')
    pieces = []                                 # (address, data), each at most chunk
    for addr, data in segs:
        mark = data.find(NAMEMARK.encode())
        off = 0
        while off < len(data):
            n = min(chunk, len(data) - off)
            end = mark + len(NAMEMARK) + 1 + NAMEFLD    # the field: mark .. end
            if mark >= 0 and mark < off + n < end:
                n = mark - off                  # it would be cut: cut before it instead
            pieces.append((addr + off, data[off:off + n])); off += n
    out = []
    for i, (addr, data) in enumerate(pieces):
        more = 0xFFFF if i < len(pieces) - 1 else 0
        out.append(more.to_bytes(2, 'big') + (len(data) + 6).to_bytes(2, 'big') + addr.to_bytes(2, 'big') + data)
    return out

def assemble_engine(out_name='TXAE1'):
    """Assemble the engine (with the current gen/storysrc.a99) into E/A 5
    files build/<out_name>.. and return their segments."""
    with open(os.path.join(ROOT, 'src/gen/badops.a99'), 'w') as f:
        f.write('* badops.a99 - GENERATED by tools/build.py: OPTAB entries >68->FF\n')
        for i in range(0x68, 0x100, 8):
            f.write('       DATA ' + ','.join(['BADOP'] * 8) + '\n')
    stem = out_name[:-1]
    for f in glob.glob(os.path.join(B, stem + '?')):
        os.remove(f)
    run([sys.executable, XAS, '-R', '-i', '-L', '../build/engine.lst', '-E', '../build/engine.equ', '-o', '../build/' + out_name, 'txaeng.a99'],
        cwd=os.path.join(ROOT, 'src'))
    segs = ea5_segments(out_name)
    for addr, data in segs:
        if addr == 0x2000 and addr + len(data) > 0x2FFE:
            sys.exit('the kernel reaches >2FFE (AMSSIZ uses it)')
        if addr == 0xA000 and addr + len(data) > 0xD000:
            sys.exit(f'the resident engine ends at >{addr + len(data):04X}, past >D000 (window D)')
        if addr == 0x3000 and addr + len(data) > 0x3800:
            sys.exit(f'the startup segment ends at >{addr + len(data):04X}, past >3800 (the variables, which START clears)')
    fend = symbols(os.path.join(B, 'engine.equ')).get('FASTND', 0)
    if fend > 0x83E0:
        sys.exit(f'the scratchpad block ends at >{fend:04X}, past >83E0 (the GPL workspace)')
    return segs

def gen_workbench_tables():
    """src/gen/opcodes.a99 (OP.name EQU code, from opcodes.py, COPYed at the
    top: equates cannot look ahead) and src/gen/bops.a99 (each built-in
    function's opcode, a byte each in sema.py's BUILTINS order, which is
    BUILTN's in wsym.a99), for the workbench's code generator."""
    sys.path.insert(0, os.path.join(ROOT, 'tools'))
    from txc.opcodes import OPS, PROP_STR, PROP_ROUTINE, PROP_VALUES
    from txc.sema import BUILTINS
    with open(os.path.join(ROOT, 'src/gen/opcodes.a99'), 'w') as f:
        f.write('* opcodes.a99 - GENERATED by tools/build.py from tools/txc/opcodes.py\n')
        for code, name, *_ in OPS:
            f.write(f'OP.{name:<9} EQU  >{code:02X}\n')
        f.write(f'PK.STR    EQU  {PROP_STR}\nPK.ROUT   EQU  {PROP_ROUTINE}\nPK.VALS   EQU  {PROP_VALUES}\n')
        from txc.opcodes import HDR, HEADER_SIZE, MAGIC, FORMAT_VERSION, OBJ_ENTRY
        for field, off in HDR.items():
            f.write(f'H.{field.upper():<14} EQU  {off}\n')
        f.write(f'H.SIZE     EQU  {HEADER_SIZE}\nOBJENT     EQU  {OBJ_ENTRY}\nFMTVER     EQU  {FORMAT_VERSION}\n')
        f.write(f'MAGIC1     EQU  >{MAGIC[0]:02X}{MAGIC[1]:02X}\nMAGIC2     EQU  >{MAGIC[2]:02X}{MAGIC[3]:02X}\n')
        from txc.codegen import MAX_IMAGE
        f.write(f'IMGMAXH    EQU  {MAX_IMAGE >> 16}            the story image at most (codegen.py MAX_IMAGE): high word\n')
    with open(os.path.join(ROOT, 'src/gen/bops.a99'), 'w') as f:
        f.write('* bops.a99 - GENERATED by tools/build.py: the built-ins\' opcodes, in BUILTINS order\nBOPS\n')
        for name, (op, n, value) in BUILTINS.items():
            f.write(f'       BYTE OP.{op:<9} {name}\n')
        f.write('       EVEN\n')

def workbench_cart(name='TXA WORKBENCH'):
    """The workbench cartridge (src/wbench.a99, M5): (cart bytes, segments).
    The resident part must end below >B000.  Overlay n (code assembled to
    run at >B000, labels OVnEND at its end) is staged in the image from
    >4000 (overlays 1-4) or in the second assembly from >0000 (5 on), and
    goes in cartridge bank n; the workbench copies it to >B000 when it is
    needed (OVSEL)."""
    gen_workbench_tables()
    for f in glob.glob(os.path.join(B, 'WBENC?')):
        os.remove(f)
    run([sys.executable, XAS, '-R', '-i', '-L', '../build/wbench.lst', '-E', '../build/wbench.equ', '-o', '../build/WBENC1', 'wbench.a99'],
        cwd=os.path.join(ROOT, 'src'))
    sy = symbols(os.path.join(B, 'wbench.equ'))
    if sy['WKEND'] > 0x2FFE:
        sys.exit(f'the workbench kernel window ends at >{sy["WKEND"]:04X}, past >2FFE')
    if sy['WBEND'] > 0xB000:
        sys.exit(f'the resident workbench ends at >{sy["WBEND"]:04X}, past >B000 (the overlays)')
    # the second assembly: overlays 5 on, with the first one's symbols
    import re
    res = []
    text = open(os.path.join(B, 'wbench.equ')).read()
    for sym, val in re.findall(r'^([\w.]+):\s*\n\s+equ\s+>([0-9A-Fa-f]{4})', text, re.M):
        v = int(val, 16)                  # (sym, not name: name is the cartridge's title)
        if 0xB000 <= v < 0xD000:          # an overlay's own label: not here
            continue
        res.append(f'{sym.upper():<12} EQU  >{v:04X}')
    with open(os.path.join(ROOT, 'src/gen/wres.a99'), 'w') as f:
        f.write('* wres.a99 - GENERATED by tools/build.py: wbench.a99\'s symbols for wovl.a99\n' + '\n'.join(res) + '\n')
    for f in glob.glob(os.path.join(B, 'WOVL?')):
        os.remove(f)
    run([sys.executable, XAS, '-R', '-i', '-L', '../build/wovl.lst', '-E', '../build/wovl.equ', '-o', '../build/WOVL1', 'wovl.a99'],
        cwd=os.path.join(ROOT, 'src'))
    with open(os.path.join(B, 'wbench.equ'), 'a') as f:     # the tests read one symbol file
        f.write(open(os.path.join(B, 'wovl.equ')).read())
    sy = symbols(os.path.join(B, 'wbench.equ'))
    staged, real = bytearray(0x6000), []
    for addr, data in ea5_segments('WBENC1'):
        if 0x4000 <= addr < 0xA000:
            staged[addr - 0x4000: addr - 0x4000 + len(data)] = data
        else:
            real.append((addr, data))
    staged2 = bytearray(0x10000)
    for addr, data in ea5_segments('WOVL1'):
        staged2[addr: addr + len(data)] = data
    banks, pos, n = [], 0, 1                    # overlay n goes in bank n (M6): the
    while f'OV{n}END' in sy:                    # workbench copies it to >B000 itself
        if n == 5:
            if pos > 0x6000:
                sys.exit(f'overlays 1-4 take {pos} bytes, past their staging room (>4000->9FFF)')
            staged, pos = staged2, 0          # overlays 5 on: the second assembly's
        size = sy[f'OV{n}END'] - 0xB000
        if size > 0x2000:
            sys.exit(f'workbench overlay {n} is {size} bytes, more than 8K')
        banks.append(bytes(staged[pos:pos + size]))
        pos += size; n += 1
    # the generic engine (M6 part 3), in the banks after the overlays, for
    # Build: its files one after another; overlay 9's ENGTAB says where
    eng = generic_engine_files()
    blob = b''.join(eng)
    first = len(banks) + 1
    namefile = next(i for i, f in enumerate(eng) if NAMEMARK.encode() in f)
    nameoff = eng[namefile].find(NAMEMARK.encode()) + len(NAMEMARK)
    assert len(eng) <= 9, 'the engine has more than 9 files'
    tab = [len(eng), first, namefile] + [len(f) for f in eng] + [0] * (9 - len(eng)) + [nameoff]
    o = sy['ENGTAB'] - 0xB000
    b9 = bytearray(banks[8])
    b9[o:o + 2 * len(tab)] = b''.join(v.to_bytes(2, 'big') for v in tab)
    banks[8] = bytes(b9)
    # overlay 10's TPENG (test-play): the same, and where STMODE is
    esy = symbols(os.path.join(B, 'engine.equ'))
    stm = esy['STMODE']
    stfile = next(i for i, f in enumerate(eng)
                  if int.from_bytes(f[4:6], 'big') <= stm < int.from_bytes(f[4:6], 'big') + len(f) - 6)
    tab10 = tab + [stfile, stm - int.from_bytes(eng[stfile][4:6], 'big')]
    o = sy['TPENG'] - 0xB000
    b10 = bytearray(banks[9])
    b10[o:o + 2 * len(tab10)] = b''.join(v.to_bytes(2, 'big') for v in tab10)
    banks[9] = bytes(b10)
    banks += [blob[i:i + 0x2000] for i in range(0, len(blob), 0x2000)]
    segs = list(real)
    cart, _ = cart_from_segments(segs, name, b'', pre=banks)
    return cart, segs

def engine_cart(story_image, name='TXA STORY', pictures=b'', sounds=b''):
    """Assemble the engine and build a cartridge carrying story_image.
    Two passes: the engine's size decides the story's first bank."""
    os.makedirs(os.path.join(ROOT, 'src/gen'), exist_ok=True)
    if not os.path.exists(os.path.join(ROOT, 'src/gen/font.a99')):
        subprocess.run([sys.executable, 'tools/mkfont.py'], cwd=ROOT, check=True)
    with open(os.path.join(ROOT, 'src/gen/badops.a99'), 'w') as f:
        f.write('* badops.a99 - GENERATED by tools/build.py: OPTAB entries >68->FF\n')
        for i in range(0x68, 0x100, 8):
            f.write('       DATA ' + ','.join(['BADOP'] * 8) + '\n')
    check_ramvars()
    blob, picpg, sndpg = story_blob(story_image, pictures, sounds)
    first = None
    for _ in range(3):
        write_storysrc(blob, first or 1, picpg=picpg, sndpg=sndpg)
        segs = assemble_engine()
        cart, f2 = cart_from_segments(segs, name, blob)
        if f2 == first:
            return cart, segs
        first = f2
    sys.exit('engine build did not settle')

def symbols(equ):
    """Label -> address from xas99's -E output ("label:" then "equ >XXXX")."""
    import re
    syms, last = {}, None
    for line in open(equ):
        m = re.match(r'^(\w+):\s*$', line)
        if m:
            last = m.group(1).upper(); continue
        m = re.match(r'^\s+equ\s+>([0-9A-Fa-f]{4})', line)
        if m and last:
            syms[last] = int(m.group(1), 16); last = None
    return syms

def main():
    check_ramvars()
    os.makedirs(B, exist_ok=True)
    os.makedirs(os.path.join(ROOT, 'src/gen'), exist_ok=True)   # generated files (not in git)
    env = dict(os.environ, PYTHONPATH=os.path.join(ROOT, 'tools'))
    subprocess.run([sys.executable, 'tools/mkfont.py'], cwd=ROOT, check=True)
    subprocess.run([sys.executable, 'tools/mkpics.py'], cwd=ROOT, check=True, env=env, capture_output=True)
    for f in glob.glob(os.path.join(B, 'TXAP*')):
        os.remove(f)
    out = run([sys.executable, XAS, '-R', '-i', '-L', '../build/probe.lst', '-o', '../build/TXAP1', 'txaprobe.a99'],
              cwd=os.path.join(ROOT, 'src'))
    segs = ea5_segments('TXAP1')
    for addr, data in segs:
        end = addr + len(data)
        print(f'segment >{addr:04X}->{end - 1:04X}  {len(data)} bytes')
        if addr == 0x2000 and end > 0x2FFE:     # AMSSIZ overwrites >2FFE while it runs
            sys.exit('the kernel reaches >2FFE, which AMSSIZ uses while it counts SAMS pages')
        if addr >= 0xA000 and end > 0xE000:
            sys.exit('resident program runs into >E000 (the SAMS sizing window)')
    assert segs[0][0] == 0x2000, 'the first E/A 5 file must be the kernel at >2000 (KENTRY)'
    # the disk image
    dsk = os.path.join(B, 'txaprobe.dsk')
    if os.path.exists(dsk):
        os.remove(dsk)
    names = sorted(os.path.basename(f) for f in glob.glob(os.path.join(B, 'TXAP?')))
    run([sys.executable, XDM, dsk, '-X', 'sssd', '-n', 'TXAPROBE'])
    run([sys.executable, XDM, dsk, '-a'] + names + ['-f', 'PROGRAM'], cwd=B)
    # the cartridge: banks 1.. hold the image, split into per-bank pieces
    image, pieces = bytearray(), []
    for addr, data in segs:
        off = 0
        while off < len(data):
            pos = len(image)
            bank, boff = 1 + pos // 0x2000, pos % 0x2000
            n = min(len(data) - off, 0x2000 - boff)
            pieces.append((bank, 0x6000 + boff, addr + off, n))
            image += data[off:off + n]; off += n
    with open(os.path.join(ROOT, 'src/gen/cartsegs.a99'), 'w') as f:
        f.write('* cartsegs.a99 - GENERATED by tools/build.py: bank, window address, RAM address, bytes\nSEGTAB\n')
        for p in pieces:
            f.write('       DATA %d,>%04X,>%04X,%d\n' % p)
        f.write('       DATA >FFFF\n')
    with open(os.path.join(ROOT, 'src/gen/cartname.a99'), 'w') as f:
        f.write("* cartname.a99 - GENERATED by tools/build.py: the menu name\n       BYTE 9\n       TEXT 'TXA PROBE'\n")
    run([sys.executable, XAS, '-R', '-b', '-o', '../build/cartldr.bin', 'cartldr.a99'], cwd=os.path.join(ROOT, 'src'))
    ldr = open(os.path.join(B, 'cartldr.bin'), 'rb').read()
    assert len(ldr) <= 0x2000
    nb = 1 + (len(image) + 0x1FFF) // 0x2000
    banks = 1
    while banks < nb:
        banks *= 2                     # FinalGROM images: a power of two of 8K banks
    cart = bytearray(ldr.ljust(0x2000, b'\0')) + image.ljust((banks - 1) * 0x2000, b'\0')
    open(os.path.join(B, 'txaprobe8.bin'), 'wb').write(cart)
    print(f'build/TXAP1..  build/txaprobe.dsk  build/txaprobe8.bin ({len(cart) // 1024}K, {banks} banks)')

if __name__ == '__main__':
    main()
