def lib_attrs():
    out = []
    for m in re.finditer(r'^ATTRIBUTE ([^!\n]*)', src('lib/libdefs.txa'), re.M):
        out += m.group(1).split()
    return out
def lib_props():
    out = []
    for m in re.finditer(r'^PROPERTY ([^!\n]*?)\s*(?:!\s*(.*))?$', src('lib/libdefs.txa'), re.M):
        names = m.group(1).split()
        for n in names:
            note = m.group(2) if (len(names) == 1 and m.group(2)) else PROP_DESC.get(n)
            if note is None and n in ('S', 'E', 'W', 'NE', 'NW', 'SE', 'SW', 'UP', 'DOWN', 'INSIDE', 'OUTSIDE'):
                note = 'an exit (see N)'
            out.append((n, note))
    return out
def lib_globals():
    return [(m.group(1), m.group(2) or '', m.group(3).strip())
            for m in re.finditer(r'^GLOBAL (\w+)\s*(?:=\s*(\S+))?\s*!\s*(.*)$', src('lib/libdefs.txa'), re.M)]
def lib_verbs():
    """[(action, verbs, grammar)] in the library's order."""
    out = []
    for f in LIB_FILES:
        for m in re.finditer(r'^VERB ((?:"[^"]*"\s*)+)\n(.*?)^END', src(f), re.M | re.S):
            words = re.findall(r'"([^"]*)"', m.group(1))
            for line in m.group(2).splitlines():
                g = re.match(r'\s*(.*?)\s*->\s*(\w+)', line)
                if g:
                    out.append((g.group(2), words, g.group(1)))
    return out
def lib_routines():
    """Routines with a comment above them: (file, name, params, comment)."""
    out = []
    for f in LIB_FILES:
        lines = src(f).splitlines()
        for i, l in enumerate(lines):
            m = re.match(r'^ROUTINE (\w+)\s*(.*)$', l)
            if not m or m.group(1).endswith('Sub'):
                continue
            j = i - 1; com = []
            while j >= 0 and lines[j].startswith('!'):
                com.insert(0, lines[j][1:].strip()); j -= 1
            text = re.sub(r'-{4}\s*[^-]*?-{4,}', '', ' '.join(com)).strip()
            if text:
                out.append((f, m.group(1), m.group(2).strip(), text))
    return out

