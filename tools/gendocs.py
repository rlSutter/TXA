#!/usr/bin/env python3
"""gendocs.py - the Technical Reference (M7), generated from the source so
that it cannot drift: docs/TECHNICAL-REFERENCE.md.  The tables (the header,
every opcode, the RAM variables, the SAMS pages, the video memory, the
overlays, the engine's segments) and the format descriptions (the save
file, the picture area, the run-length codes, the sound area, TI Artist
pictures) are read from the files that define them; the prose around them
says how they fit together.  tests/docs_test.py regenerates it and fails
if the committed copy differs.

  python3 tools/gendocs.py          writes docs/TECHNICAL-REFERENCE.md
  python3 tools/gendocs.py --check  exits 1 if it would change"""
import os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
from txc import opcodes as O

def src(path):
    return open(os.path.join(ROOT, path), encoding='latin-1').read()

def docstring(path):
    s = src(path)
    m = re.search(r'"""(.*?)"""', s, re.S)
    return m.group(1).strip()

def code(text):
    return '```\n' + text.rstrip() + '\n```\n'

def esc(t):
    return t.replace('|', '\\|')

def header_table():
    rows = []
    for m in re.finditer(r"^\s+'(\w+)':\s*(\d+),\s*#\s*(.*)$", src('tools/txc/opcodes.py'), re.M):
        name, off, note = m.group(1), int(m.group(2)), m.group(3)
        rows.append(f'| {off} | `{name}` | {esc(note)} |')
    assert len(rows) == len(O.HDR), 'every header field must carry a comment in opcodes.py'
    return '| Offset | Field | Meaning |\n| --- | --- | --- |\n' + '\n'.join(rows) + '\n'

def opcode_table():
    rows = [f'| >{c:02X} | `{n}` | {ops or "-"} | {esc(st) or "-"} | {esc(d)} |' for c, n, ops, st, d in O.OPS]
    return '| Code | Name | Operands | Stack | Meaning |\n| --- | --- | --- | --- | --- |\n' + '\n'.join(rows) + '\n'

def save_format():
    s = src('tools/txc/opcodes.py')
    a = s.index('# ---- the save file'); b = s.index('SAVE_MAGIC =')
    lines = [l[2:] if l.startswith('# ') else l.lstrip('#') for l in s[a:b].splitlines()[1:]]
    return code('\n'.join(lines))

def equs(path, base):
    """(name, offset, note) for each 'NAME EQU base+>off  note' in path."""
    out = []
    text = src(path)
    for m in re.finditer(r'^(\w+)\s+EQU\s+' + base + r'\+>([0-9A-F]+)\s*(.*)$', text, re.M):
        out.append((m.group(1), int(m.group(2), 16), note_at(text, m)))
    return sorted(out, key=lambda t: t[1])

def note_at(text, m):
    """An EQU's comment, with the lines that carry it on ('*' and spaces)."""
    note = m.group(m.lastindex).strip()
    rest = text[m.end():].split('\n')[1:]
    for line in rest:
        c = re.match(r'^\*\s{20,}(\S.*)$', line)
        if not c:
            break
        note += ' ' + c.group(1).strip()
    return note

def const_equs(path, names):
    out = []
    text = src(path)
    for m in re.finditer(r'^(\w+)\s+EQU\s+(>?[0-9A-F]+|\d+)\s*(.*)$', text, re.M):
        if m.group(1) in names:
            v = m.group(2); v = int(v[1:], 16) if v.startswith('>') else int(v)
            out.append((m.group(1), v, note_at(text, m)))
    return out

def ramvar_table():
    rows = [f'| >{off:03X} | `{n}` | {esc(note)} |' for n, off, note in equs('src/defs.a99', 'RAMVAR')]
    return '| RAMVAR+ | Name | Meaning |\n| --- | --- | --- |\n' + '\n'.join(rows) + '\n'

def pages_table():
    names = ['UNDLST', 'UNDRNG', 'SBPAGE', 'HISPG', 'PRPAGE', 'STPAGE']
    rows = [f'| {v} | `{n}` | {esc(note)} |' for n, v, note in sorted(const_equs('src/defs.a99', names), key=lambda t: t[1])]
    return '| Page | Name | Holds |\n| --- | --- | --- |\n' + '\n'.join(rows) + '\n'

def overlay_table():
    found = {}
    for m in re.finditer(r'^\* overlay (\d+): (.*)$', src('src/wbench.a99'), re.M):
        found[int(m.group(1))] = ('-', m.group(2))
    for m in re.finditer(r'^\s+B\s+@(\w+)\s+overlay (\d+): (.*)$', src('src/wovl.a99'), re.M):
        found[int(m.group(2))] = (f'`{m.group(1)}`', m.group(3))
    rows = [f'| {n} | {e} | {esc(w)} |' for n, (e, w) in sorted(found.items())]
    return '| Overlay | Entry | What |\n| --- | --- | --- |\n' + '\n'.join(rows) + '\n'

def vram_table():
    names = ['NAMTAB', 'ATRTAB', 'SPRATT', 'PATTAB', 'SPRPAT', 'FBUF', 'BMLDAT', 'PABADR']
    rows = [f'| >{v:04X} | `{n}` | {esc(note)} |' for n, v, note in sorted(const_equs('src/defs.a99', names), key=lambda t: t[1])]
    return '| Address | Name | Holds |\n| --- | --- | --- |\n' + '\n'.join(rows) + '\n'

def generate():
    p = []
    p.append('# TXA Technical Reference\n')
    p.append('Generated by `tools/gendocs.py` from the source; do not edit by hand. '
             'The tables and format descriptions are read from the files that define them '
             '(`tools/txc/opcodes.py`, `src/defs.a99`, `src/wovl.a99`, and the tools\' own '
             'descriptions), so this reference changes when they do.\n')
    p.append('## 1. The story image\n')
    p.append(f'A story is one image of at most 256K: a {O.HEADER_SIZE}-byte header, the dynamic area '
             '(the object table, property tables, globals and arrays: the part a game changes, and the part '
             'saved), then the static tables (dictionary, grammar, actions, text substitutions), which must lie '
             'in the first 64K because the header holds 16-bit offsets to them, then the routines and strings, '
             'each on a 4-byte boundary and named by packed address (byte address / 4). All words are '
             f'big-endian. The magic is `{O.MAGIC.decode()}`, format version {O.FORMAT_VERSION}.\n')
    p.append('### The header\n')
    p.append(header_table())
    p.append(f'### Objects and properties\n')
    p.append(f'Each object has a {O.OBJ_ENTRY}-byte entry: parent, sibling and child (words: object numbers, '
             '0 for none), 6 bytes of attributes (48, the first attribute in the high bit of the first byte), '
             'and the offset of its property table. A property table starts with the object\'s short name (a '
             'packed string address, 0 for none), then its properties in ascending number, each a byte '
             'holding the number and its kind, a count byte, and the values; a zero byte ends the table. The '
             f'kinds: >{O.PROP_VALUES:02X} words (count words follow), >{O.PROP_STR:02X} a string (one packed address), '
             f'>{O.PROP_ROUTINE:02X} a routine (one packed address).\n')
    p.append('### Globals, arrays and the dictionary\n')
    p.append('The globals are 240 words (variables 16-255). The arrays have a directory (a count, then each '
             'array\'s offset and length in words) and then their data; the parser\'s tables (VERBTAB, '
             'GRAMTAB, ACTSUB, DICTVERB) are arrays the compiler fills. The dictionary is a count, then '
             '14-byte entries in byte order: 12 characters, zero padded; a flags byte (1 noun, 2 verb, 4 '
             'preposition); the verb\'s number. A word\'s number is its place in the dictionary, from 1.\n')
    p.append('### Text\n')
    p.append('A string is a run of bytes ended by 0: 10 is a line break, 32-126 themselves, and >80->FF the '
             'text substitution with that index (0-127), whose words the substitution table holds (128 offsets '
             'from the table\'s start, 0 for unused, then the words, each ended by 0). The compiler chooses the '
             'substitutions from the game\'s own strings.\n')
    p.append('### The dynamic area and the checksum\n')
    p.append('The dynamic area is at most 16384 bytes (the engine keeps an UNDO copy of it in four SAMS '
             'pages). The checksum is the sum of every byte after the header, mod 65536; a save file names '
             'the checksum and release of the story it belongs to.\n')
    p.append('## 2. The instruction set\n')
    p.append(code(docstring('tools/txc/opcodes.py').split('The machine\n-----------\n', 1)[1]))
    p.append(f'{len(O.OPS)} opcodes:\n\n')
    p.append(opcode_table())
    p.append('## 3. File formats\n')
    p.append('### The save file\n')
    p.append(save_format())
    p.append('### Run-length packing (pictures)\n')
    p.append(code(docstring('tools/rlepack.py')))
    p.append('### The picture area\n')
    p.append(code(docstring('tools/txpics.py')))
    p.append('### TI Artist pictures\n')
    p.append(code(docstring('tools/tiartist.py')))
    p.append('### Music and sound effects\n')
    p.append(code(docstring('tools/txsound.py')))
    p.append('The notation they are written in, TXA music notation 1.0, is described in `docs/MUSIC.md`.\n')
    p.append('### Workbench files\n')
    p.append('- **Source files**: DIS/VAR 80, one line a record.\n'
             '- **Story files** PREFIX + S + two digits: the image in 4K PROGRAM files.\n'
             '- **Picture files** PREFIX + P + two digits: the picture area in 4K PROGRAM files.\n'
             '- **Music files** PREFIX + M + two digits: the sound area in 4K PROGRAM files.\n'
             '- **Engine files** PREFIX + 1 to 5: the engine, E/A 5 (memory image) files; load the first.\n'
             '- **Scripts** PREFIX + R + a digit (RECORD, REPLAY): DIS/VAR 80, one command a record.\n'
             '- **Saved games**: one PROGRAM file, the save file above.\n'
             '- **NAME_T**: a TI Artist picture\'s fitting, one DIS/VAR 80 line, `crop N` or `squeeze`.\n'
             '- **DSK1.TXAOPT**: the workbench\'s options, DIS/VAR 80 lines `colours N` (0-4), `font normal` or '
             '`font bold`, `library DSK2. DSK3.`.\n')
    p.append('## 4. The TI engine: memory\n')
    p.append('The engine runs from 32K memory expansion and SAMS. Its code: the kernel at >2000->2FFD (video, '
             'keyboard, disk, sound, pictures), the start-up code and font at >3000 (overwritten by the value '
             'stack once the game runs), and the resident engine at >A000->CFFF (the VM, output, input, UNDO, '
             'saving). Windows >D000, >E000 and >F000 (SAMS pages mapped in as needed) reach the story, '
             'pictures and the UNDO records. The RAM variables:\n\n')
    p.append(ramvar_table())
    p.append('### SAMS pages\n')
    p.append('Pages 0-15 are the memory map itself (identity); 4-9 are never mapped (their windows are ROM '
             'and devices). The engine\'s own:\n\n')
    p.append(pages_table())
    p.append('The story occupies pages from 32; the picture area, then the sound area, follow it.\n')
    p.append('### Video memory\n')
    p.append(vram_table())
    p.append('The disk controller keeps its buffers from about >37D8 up, set by its power-up routine. The '
             'picture\'s bitmap (>2800->3FFF) overwrites them, so the engine runs a controller\'s power-up '
             'again before a disk call (never a TIPI\'s, which only resets its Pi), and keeps pictures off '
             'while a RECORD or REPLAY script file is open.\n')
    p.append('## 5. The workbench\n')
    p.append('The workbench is a 256K cartridge (FinalGROM 99). It runs from RAM: a resident part at '
             '>A000->AFFF, a kernel window at >2000->2FFE, and one overlay at a time at >B000, copied from its '
             'cartridge bank (the bank\'s last word holds its length).\n\n')
    p.append(overlay_table())
    p.append('## 6. F18A settings\n')
    p.append('Both programs refuse to start without an F18A or PICO9918 and SAMS. They use Text 80 with 30 '
             'rows and position attributes (VR50 >02), and the F18A\'s bitmap layer for pictures: VR32 the '
             'bitmap\'s address /64, VR33 and VR34 its position, VR35 0 (256 wide), VR36 96 rows, VR31 on with '
             'priority, fat pixels for 16 colours, and palette 32-47 (the picture\'s own colours). The '
             'workbench\'s text is palette 14 on 1, which its options change.\n')
    p.append('## 7. Known emulator differences\n')
    p.append('- js99er draws the bitmap layer doubled sideways in 80 columns (reported to its author).\n'
             '- js99er\'s TI disk controller setting misreads double-density images; its "Generic Disk" '
             'setting reads them. TI\'s own controller reads single density only, so TXA\'s disks are 180K '
             'single density.\n')
    return '\n'.join(p)

if __name__ == '__main__':
    out = generate()
    path = os.path.join(ROOT, 'docs', 'TECHNICAL-REFERENCE.md')
    if '--check' in sys.argv:
        sys.exit(0 if os.path.exists(path) and open(path).read() == out else 1)
    open(path, 'w').write(out)
    print(f'{path}: {len(out)} characters')
