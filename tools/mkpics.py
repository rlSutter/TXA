#!/usr/bin/env python3
"""mkpics.py - the M0 test pictures for the bitmap layer.

PIC2: 256 x 96, 2 bits a pixel, four colours (palette entries 32-35).
PIC4: 128 x 96 fat pixels, 4 bits a pixel, sixteen colours (32-47).
Both are test cards: a one-pixel cream border, amber corner marks and a
tick every 32 bitmap pixels along the top and bottom edges, so cropping,
position and pixel width can be read off a screen photo.  Written to
src/gen/pics.a99 (run-length packed, tools/rlepack.py) with PNG previews
in build/."""
import math, os
from PIL import Image, ImageDraw
from rlepack import pack, unpack

def rgb12(c):
    r, g, b = (int(c[i:i + 2], 16) for i in (1, 3, 5))
    return (round(r / 17) << 8) | (round(g / 17) << 4) | round(b / 17)

PAL2 = ['#14203c', '#3c6e82', '#e0a040', '#f0e6cc']        # night, slate, amber, cream
PAL4 = PAL2 + ['#0a1020', '#20385a', '#52869a', '#78a8b4', '#a8c8c8',
               '#2a4a30', '#4a7040', '#806030', '#b07838', '#f0c060', '#c04830', '#ffffff']

def card(w, h, sx):
    """Draw the shared test card at w x h; sx = screen pixels per bitmap pixel."""
    im = Image.new('P', (w, h), 0)
    d = ImageDraw.Draw(im)
    for y in range(h):                       # sky: night to slate, dithered band
        for x in range(w):
            t = (y - 30) / 30
            if t > 0 and ((x + y) % 2 == 0 or t > 0.6):
                im.putpixel((x, y), 1)
    mx = int(w * 0.78); my = 24; rx, ry = 10 // sx, 10   # round on screen: fat pixels are 2 wide
    d.ellipse([mx - rx, my - ry, mx + rx, my + ry], fill=3)
    pts = [(0, 70)] + [(x, int(66 - 8 * math.sin(x / w * 7) - 5 * math.sin(x / w * 17))) for x in range(0, w + 1, 2)] + [(w, h), (0, h)]
    d.polygon(pts, fill=0)
    lx = w // 4                               # a lighthouse
    d.rectangle([lx - 3 // sx, 40, lx + 3 // sx + 1, 72], fill=3)
    d.rectangle([lx - 2 // sx, 36, lx + 2 // sx + 1, 40], fill=2)
    d.rectangle([0, 0, w - 1, h - 1], outline=3)
    for x in range(0, w, 32 // sx):          # a tick every 32 screen pixels
        d.line([x, 0, x, 4], fill=3); d.line([x, h - 5, x, h - 1], fill=3)
    for (cx, cy, dx, dy) in [(1, 1, 1, 1), (w - 2, 1, -1, 1), (1, h - 2, 1, -1), (w - 2, h - 2, -1, -1)]:
        d.line([cx, cy, cx + 8 // sx * dx, cy], fill=2); d.line([cx, cy, cx, cy + 8 * dy], fill=2)
    return im

def pic2():
    return card(256, 96, 1)

def pic4():
    im = card(128, 96, 2)
    d = ImageDraw.Draw(im)
    for i in range(16):                      # colour bars: every palette entry
        d.rectangle([4 + i * 7, 84, 4 + i * 7 + 6, 91], fill=i)
    for x in range(1, 127):                  # a warm glow on the water line
        im.putpixel((x, 72), 13 if x % 3 else 12)
    return im

def encode(im, bpp):
    w, h = im.size; px = im.load(); out = bytearray()
    per = 8 // bpp
    for y in range(h):
        for x0 in range(0, w, per):
            b = 0
            for k in range(per):
                b = (b << bpp) | (px[x0 + k, y] & ((1 << bpp) - 1))
            out.append(b)
    return bytes(out)

def preview(im, pal, scale_x, path):
    im = im.copy(); flat = []
    for c in pal: flat += [int(c[i:i + 2], 16) for i in (1, 3, 5)]
    im.putpalette(flat + [0] * (768 - len(flat)))
    im.convert('RGB').resize((im.size[0] * scale_x * 2, im.size[1] * 2), Image.NEAREST).save(path)

def asm_bytes(label, data):
    lines = [label]
    for i in range(0, len(data), 16):
        lines.append('       BYTE ' + ','.join('>%02X' % b for b in data[i:i + 16]))
    return lines

if __name__ == '__main__':
    os.makedirs('build', exist_ok=True)
    a, b = pic2(), pic4()
    d2, d4 = encode(a, 2), encode(b, 4)
    assert len(d2) == len(d4) == 6144
    p2, p4 = pack(d2), pack(d4)
    assert unpack(p2) == d2 and unpack(p4) == d4
    open('build/pic2.raw', 'wb').write(d2); open('build/pic4.raw', 'wb').write(d4)
    preview(a, PAL2, 1, 'build/pic2-preview.png'); preview(b, PAL4, 2, 'build/pic4-preview.png')
    out = ['* pics.a99 - GENERATED by tools/mkpics.py: the M0 test pictures.',
           '* Do not edit: rerun the tool.  Palettes are 12-bit >0RGB words.',
           'PAL2   DATA ' + ','.join('>%04X' % rgb12(c) for c in PAL2),
           'PAL4   DATA ' + ','.join('>%04X' % rgb12(c) for c in PAL4[:8]),
           '       DATA ' + ','.join('>%04X' % rgb12(c) for c in PAL4[8:])]
    out += asm_bytes('PIC2', p2) + asm_bytes('PIC4', p4) + ['       EVEN']
    open('src/gen/pics.a99', 'w').write('\n'.join(out) + '\n')
    print(f'PIC2 {len(p2)} bytes packed, PIC4 {len(p4)} bytes packed (6144 each raw)')
